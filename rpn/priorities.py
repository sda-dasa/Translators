#!/usr/bin/env python3
# -*- coding: utf-8 -*-

from typing import Dict


class OperatorPriority:
    """
    Таблица приоритетов операций (Таблицы 2.1-2.8 из методички)
    """

    PRIORITIES: Dict[str, int] = {
        # Наивысший приоритет
        '**': 8,

        # Умножение и деление (приоритет 7)
        '*': 7,
        '/': 7,
        '%': 7,

        # Сложение и вычитание (приоритет 6)
        '+': 6,
        '-': 6,

        # Операции отношения (приоритет 5)
        '<': 5,
        '>': 5,
        '<=': 5,
        '>=': 5,
        '==': 5,
        '!=': 5,
        '<>': 5,

        # Логические операции (приоритет 4)
        '&&': 4,
        '!': 4,

        # Логическое ИЛИ (приоритет 3)
        '||': 3,

        # Оператор присваивания (приоритет 2)
        ':=': 2,

        # Безусловный переход (приоритет 2)
        'GOTO': 2,

        # THEN и ELSE (приоритет 1)
        'THEN': 1,
        'ELSE': 1,

        # Открывающие конструкции (приоритет 0)
        '(': 0,
        '[': 0,
        '{': 0,
        'IF': 0,
        'WHILE': 0,
        'PROC': 0,
        'DCL': 0,
        'END': 0,

        # Разделители
        ')': 0,
        ']': 0,
        '}': 0,
        ',': 0,
        ';': 0,
        ':': 0,
    }

    @classmethod
    def get(cls, operator: str) -> int:
        return cls.PRIORITIES.get(operator, 99)